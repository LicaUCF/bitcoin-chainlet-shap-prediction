# import the necessary libraries
import os
import warnings

import numpy as np
import pandas as pd
import shap

from sklearn.neural_network import MLPRegressor
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.pipeline import Pipeline
from sklearn.metrics import mean_squared_error, mean_absolute_percentage_error, r2_score

warnings.filterwarnings('ignore')

# local directory folder location
script_dir = os.path.dirname(os.path.abspath(__file__))
os.chdir(script_dir)

# load data files, while telling pandas to split columns by 1 or + whitespaces (sep=r'\s+')
amo_chainlets= pd.read_csv('AmoChainletsInTime.txt', sep=r'\s+')
occ_chainlets= pd.read_csv('OccChainletsInTime.txt', sep=r'\s+')
price_df = pd.read_csv('pricedBitcoin2009-2018.csv')

# strict datetime data loading (no string slicing)
if 'date' in price_df.columns:
    price_df['date']= pd.to_datetime(price_df['date'])
else:
    price_df['date']= pd.to_datetime(price_df['year'].astype(str) + '-' + price_df['day'].astype(str), format='%Y-%j')

amo_chainlets['date'] = pd.to_datetime(amo_chainlets['year'].astype(str) + '-' + amo_chainlets['day'].astype(str),
                                       format='%Y-%j')
occ_chainlets['date'] = pd.to_datetime(occ_chainlets['year'].astype(str) + '-' + occ_chainlets['day'].astype(str),
                                       format='%Y-%j')

print(f'✓ loaded {len(price_df)} price records')
print(f'✓ loaded AmoChainlets with {len(amo_chainlets)} rows')
print(f'✓ loaded OccChainlets with {len(occ_chainlets)} rows')

# 1 merge the chainlet files using BOTH occurrence and amount chainlet features
amo_cols= []
occ_cols= []
for i in range(1, 21):  #Bitcoin chainlets using a 20x20 matrix of inputs
    for j in range(1, 21):  #Bitcoin chainlets using a 20x20 matrix of outputs
        col_pair= f'{i}:{j}'
        amo_col= f'amo_{i}_{j}'
        occ_col =f'occ_{i}_{j}'
        amo_chainlets[amo_col] =amo_chainlets[col_pair]
        occ_chainlets[occ_col] =occ_chainlets[col_pair]
        amo_cols.append(amo_col)
        occ_cols.append(occ_col)

all_chainlet_cols = amo_cols + occ_cols
print(f'✓ created {len(amo_cols)} amount  and {len(occ_cols)} occurrence chainlet features')

#                      ---stop and check errors (good at 5:23pm, 11/17)---


# merge price and chainlet data chronologically on datetime, followed by aggregation
amo_subset = amo_chainlets[['date'] + amo_cols]
occ_subset = occ_chainlets[['date'] + occ_cols]
chainlet_merged = pd.merge(amo_subset, occ_subset, on='date', how='inner')
merged_df = pd.merge(price_df, chainlet_merged, on='date', how='inner')
merged_df = merged_df.sort_values('date').reset_index(drop=True)

merged_df['total_amo_volume'] = merged_df[amo_cols].sum(axis=1)
merged_df['total_occ_count'] = merged_df[occ_cols].sum(axis=1)
print(f'✓ merged dataset:{len(merged_df)} rows, {len(merged_df.columns)} columns')

# 2 aggregating, lag pricing (t-1, t-2, etc), lag chainlets, checking leakage errors--past-only ffill
merged_df =merged_df.ffill()

# lag all chainlet features by 1 day so same-day chainlets do not leak into current-day target
chainlet_lag_cols= all_chainlet_cols + ['total_amo_volume', 'total_occ_count']
merged_df[chainlet_lag_cols] = merged_df[chainlet_lag_cols].shift(1)

# time lag and avoiding leakage
lag_days =[1, 2, 3, 4, 5, 7, 14, 28, 30, 31]
for lag in lag_days:
    merged_df[f'price_lag{lag}']= merged_df['price'].shift(lag)

# shift by 1 so t is not included in stats
past_price =merged_df['price'].shift(1)
merged_df['rolling_mean_7'] = past_price.rolling(window=7).mean()
merged_df['rolling_std_7'] = past_price.rolling(window=7).std()
merged_df['price_return_1d'] = past_price.pct_change(periods=1)
merged_df['price_return_7d'] = past_price.pct_change(periods=7)
merged_df['volatility_7'] = merged_df['rolling_std_7'] / merged_df['rolling_mean_7']

# rows with NaN should be dropped
# after values are generated by lagging, clean null
df_clean = merged_df.dropna().copy().reset_index(drop=True)
print(f'✓created {len(lag_days)} lag features + rolling indicators + lagged chainlets')
print(f'✓clean dataset: {len(df_clean)}rows after dropping NaN')

# 2009-2016 constraint check to match market maturity
df_clean =df_clean[df_clean['date'] >= '2016-01-01'].copy().reset_index(drop=True)
print(f'✓ values filtered starting 2016 :{len(df_clean)} rows')
#                      ---stop and check errors (good at 7:53pm, 11/17)---


# 3 Train, Validate, Temporal Test Split (Chronological, not a random prediction)
# constraint: december, 2017=31 days

# test
train_end = '2017-10-30'
val_start = '2017-07-01'
val_end = '2017-11-30'
test_start = '2017-12-01'
test_end = '2017-12-31'
# validate
mask_train = df_clean['date'] <= train_end
mask_val = (df_clean['date'] >= val_start) & (df_clean['date'] <= val_end)
mask_test = (df_clean['date'] >= test_start) & (df_clean['date'] <= test_end)
# split
train_val_df = df_clean[mask_train].copy().reset_index(drop=True)
val_df = df_clean[mask_val].copy().reset_index(drop=True)
test_df = df_clean[mask_test].copy().reset_index(drop=True)
print(
    f'✓ Training period is 2016-01-01 to {train_end} ({len(train_val_df)} days). Validation period is {val_end} ({len(val_df)} days). Testing period is {test_end} ({len(test_df)} days).')

# is the test 31 days?
assert len(test_df) == 31, f'Validation failed. Achieved {len(test_df)}rather than 31.'

# 4 Model training, features adhering to constraints: no year, day, date
drop_cols= ['year', 'day', 'date', 'price', ''
                                            '']
features= [col for col in df_clean.columns if col not in drop_cols]

X_train= train_val_df[features]
y_train= train_val_df['price']
X_val= val_df[features]
y_val= val_df['price']
X_test= test_df[features]
y_test= test_df['price']
print(f'✓feature matrix: {X_train.shape[1]}features')

# 5 evaluation: MSE, RMSE should be low using neural networks (MLP Regression)
naive_predictions =y_test.shift(1).iloc[1:].values
naive_actuals= y_test.iloc[1:].values
naive_rmse= np.sqrt(mean_squared_error(naive_actuals, naive_predictions))
naive_mape= mean_absolute_percentage_error(naive_actuals, naive_predictions) * 100
# what is baseline, rmse, mape?
print(f'naive baseline: RMSE=${naive_rmse:.2f}')
print(f'naive baseline:MAPE={naive_mape:.2f}%')
# mlp regressor pipeline
mlp_pipeline = Pipeline([
    ('scaler', StandardScaler()),
    ('pca', PCA(n_components=15)),
    ('regressor', MLPRegressor(
        hidden_layer_sizes=(75, 50, 25),
        activation='relu',
        solver='adam',
        alpha=0.001,
        learning_rate='adaptive',
        max_iter=1025,
        early_stopping=True,
        validation_fraction=0.1,
        n_iter_no_change=20,
        random_state=51,
    ))
])
mlp_pipeline.fit(X_train, y_train)

# 6 predictions,validations,  results, Neural Network performance
X_train_full= pd.concat([X_train, X_val], axis=0).reset_index(drop=True)
y_train_full= pd.concat([y_train, y_val], axis=0).reset_index(drop=True)

mlp_pipeline.fit(X_train_full, y_train_full)
# test
# result metrics mean square error
mlp_test_preds= mlp_pipeline.predict(X_test)
mlp_test_rmse= np.sqrt(mean_squared_error(y_test, mlp_test_preds))
mlp_test_mape= mean_absolute_percentage_error(y_test, mlp_test_preds) * 100
mlp_test_r2 =r2_score(y_test, mlp_test_preds)

print('\n--- final Dec 2017 test performance (trained through Nov 30 2017) ---')
print(f'Test RMSE=${mlp_test_rmse:.2f}')
print(f'Test MAPE={mlp_test_mape:.2f}%')
print(f'Test R2={mlp_test_r2:.4f}')

print(f"{'neural network':<15} ${mlp_test_rmse:<11.2f} {mlp_test_mape:<11.2f}% {mlp_test_r2:<10.4f}")
print('test and validation performance (Dec 2017)')

predictions= mlp_test_preds
rmse= mlp_test_rmse
mape= mlp_test_mape
r2= mlp_test_r2
#                      ---stop and check errors (good at 8:05pm, 11/17)---



# 7 (XAI): SHAP explanations for 3 predictions in December 2017, wrapped in lambda fun so SHAP leaves
# Pipeline unchanged
background_summary= shap.kmeans(X_train_full, 10)
explainer =shap.KernelExplainer(lambda x: mlp_pipeline.predict(x), background_summary)

# select 3 specific days in December 2017: Dec 1 (index 0), Dec 17 (index 16), Dec 31 (index 30)
sample_indices= [0,16, 30]
shap_values =explainer.shap_values(X_test.iloc[sample_indices])

print('\n--- SHAP explanations for 3 Dec 2017 predictions ---')
for idx, test_row_idx in enumerate(sample_indices):
    pred_date= test_df.iloc[test_row_idx]['date'].strftime('%Y-%m-%d')
    actual_price =y_test.iloc[test_row_idx]
    pred_price =mlp_test_preds[test_row_idx]

#  top 3 most influential features by absolute SHAP impact
    row_shap= shap_values[idx]
    top_3_idx= np.argsort(np.abs(row_shap))[::-1][:3]

    print(f'\ndate:{pred_date} | actual:${actual_price:.2f} | predicted:${pred_price:.2f}')
    for f_idx in top_3_idx:
        fname =features[f_idx]
        fval =X_test.iloc[test_row_idx][fname]
        impact =row_shap[f_idx]
        direction= 'increased' if impact > 0 else 'decreased'
        print(f'✓ feature {fname} (val={fval:.4f}) {direction} prediction by ${abs(impact):.2f}')

# 8 deliverables: export CSV file with December 2017 predictions
submission_df = pd.DataFrame({
    'date': test_df['date'].dt.strftime('%Y-%m-%d'),
    'predicted_price':predictions
})
submission_df.to_csv('december_2017_predictions.csv', index=False)
print('\n✓saved Dec 2017 predictions to december_2017_predictions.csv')

